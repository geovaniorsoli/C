public class calcularCachorro {
    private double cachorro1;
    private double cachorro2;

    public calcularCachorro(double cachorro1, double cachorro2) {
        this.cachorro1 = 10;
        this.cachorro2 = 20;
    }

    public double calcularDoisCachorros(){
        return (cachorro1 + cachorro2) / 2;
    }

}
